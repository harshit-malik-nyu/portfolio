"""Rebuild the published demonstration from actual pipeline executions."""
import copy
import json
from pathlib import Path
import tempfile
from pipeline import connect, latest, refresh

ROOT = Path(__file__).resolve().parent
NOW = '2026-01-02T01:00:00Z'

def event(identity, kind='view', visitor='v1', order=None):
    return {'event_id': identity, 'occurred_at': '2026-01-01T10:00:00Z',
            'visitor_id': visitor, 'event': kind, 'order_id': order}

def batch(identity, events, watermark='2026-01-02T00:00:00Z'):
    return {'batch_id': identity, 'complete_through': watermark, 'events': events}

base = batch('baseline', [event('v1-view'), event('v2-view', visitor='v2'),
                          event('v1-cart', 'addtocart'), event('v1-buy', 'transaction', order='order-1')])
late = batch('late-arrival', [event('v2-buy', 'transaction', 'v2', 'order-2')])
conflict = batch('conflict', [event('v3-view', visitor='v3'), event('v1-view', visitor='wrong-owner')])
recovery = batch('recovery', [event('v3-view', visitor='v3')])
scenarios = [
 ('Baseline published', 'Two visitors, one buyer. The reporting day is closed at the source watermark.', base),
 ('Replay is harmless', 'The identical delivery is replayed. No new report version or inflated totals.', base),
 ('Late order restates history', 'A second purchase arrives for the closed day. The new report discloses the restatement.', late),
 ('Conflict blocks the batch', 'A conflicting event identity follows a valid new row. Both are rolled back; report 2 remains available.', conflict),
 ('Stale source is rejected', 'A stale completeness watermark cannot silently replace the trusted report.', batch('stale', [], '2025-12-30T00:00:00Z')),
 ('Recovery publishes a new version', 'A valid delivery succeeds after the failures. Earlier report versions remain stored.', recovery),
]
with tempfile.TemporaryDirectory() as tmp:
    db = connect(Path(tmp) / 'demo.sqlite')
    outputs = []
    for title, explanation, data in scenarios:
        outputs.append({'title': title, 'explanation': explanation, 'input': data,
                        'result': refresh(db, data, NOW), 'report': latest(db)})
    db.close()
result = {'evidence_type': 'Synthetic fixtures; results generated by pipeline.py, not manually authored',
          'as_of': NOW, 'scenarios': outputs}
(ROOT / 'demo.json').write_text(json.dumps(result, indent=2) + '\n')
(ROOT / 'demo-data.js').write_text('window.OPERATIONS_DEMO = ' + json.dumps(result, indent=2) + ';\n')
(ROOT / 'baseline.json').write_text(json.dumps(base, indent=2) + '\n')
print('Built six sequential scenarios from real SQLite refreshes.')
